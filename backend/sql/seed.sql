-- =============================================================================
-- DDL и тестовые данные для ИС аренды жилой недвижимости (Oracle Database)
-- Раздельная архитектура пользователей: LANDLORDS (Арендодатели) и TENANTS (Арендаторы)
-- =============================================================================

CREATE TABLE landlords (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR2(150) NOT NULL,
  email         VARCHAR2(150) NOT NULL UNIQUE,
  phone         VARCHAR2(30),
  password_hash VARCHAR2(255) NOT NULL
);

CREATE TABLE tenants (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR2(150) NOT NULL,
  email         VARCHAR2(150) NOT NULL UNIQUE,
  phone         VARCHAR2(30),
  password_hash VARCHAR2(255) NOT NULL
);

CREATE TABLE property_types (
  type_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE addresses (
  address_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city       VARCHAR2(100) NOT NULL,
  district   VARCHAR2(100) NOT NULL,
  street     VARCHAR2(150) NOT NULL,
  building   VARCHAR2(30)  NOT NULL,
  apartment  VARCHAR2(30),
  lat        NUMBER(9,6),
  lng        NUMBER(9,6)
);

CREATE TABLE properties (
  property_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  landlord_id   NUMBER NOT NULL REFERENCES landlords(id),
  type_id       NUMBER NOT NULL REFERENCES property_types(type_id),
  address_id    NUMBER NOT NULL REFERENCES addresses(address_id),
  title         VARCHAR2(200) NOT NULL,
  description   CLOB,
  rooms         NUMBER(3)     NOT NULL,
  area          NUMBER(8,2)   NOT NULL,
  monthly_price NUMBER(12,2)  NOT NULL,
  status        VARCHAR2(20)  DEFAULT 'AVAILABLE' NOT NULL
                CHECK (status IN ('AVAILABLE', 'RENTED', 'INACTIVE')),
  created_at    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE rental_applications (
  application_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id        NUMBER NOT NULL REFERENCES properties(property_id),
  tenant_id          NUMBER NOT NULL REFERENCES tenants(id),
  desired_start_date DATE   NOT NULL,
  lease_months       NUMBER(3) NOT NULL,
  message            VARCHAR2(1000),
  status             VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
                     CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
  created_at         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE contracts (
  contract_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id NUMBER NOT NULL REFERENCES rental_applications(application_id),
  property_id    NUMBER NOT NULL REFERENCES properties(property_id),
  tenant_id      NUMBER NOT NULL REFERENCES tenants(id),
  landlord_id    NUMBER NOT NULL REFERENCES landlords(id),
  start_date     DATE          NOT NULL,
  end_date       DATE          NOT NULL,
  monthly_amount NUMBER(12,2)  NOT NULL,
  status         VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL
                 CHECK (status IN ('ACTIVE', 'CLOSED'))
);

CREATE TABLE payments (
  payment_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  contract_id NUMBER NOT NULL REFERENCES contracts(contract_id),
  due_date    DATE          NOT NULL,
  amount      NUMBER(12,2)  NOT NULL,
  status      VARCHAR2(20)  DEFAULT 'PENDING' NOT NULL
              CHECK (status IN ('PENDING', 'PAID', 'OVERDUE')),
  paid_at     TIMESTAMP
);

