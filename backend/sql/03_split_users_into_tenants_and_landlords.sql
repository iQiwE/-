-- =============================================================================
-- Миграция 03: Разделение таблицы USERS на две сущности LANDLORDS и TENANTS
-- и обновление внешних ключей в таблицах PROPERTIES, RENTAL_APPLICATIONS, CONTRACTS
-- =============================================================================

-- 1. Создание таблицы арендодателей LANDLORDS
CREATE TABLE landlords (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR2(150) NOT NULL,
  email         VARCHAR2(150) NOT NULL UNIQUE,
  phone         VARCHAR2(30),
  password_hash VARCHAR2(255) NOT NULL
);

-- 2. Создание таблицы арендаторов TENANTS
CREATE TABLE tenants (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR2(150) NOT NULL,
  email         VARCHAR2(150) NOT NULL UNIQUE,
  phone         VARCHAR2(30),
  password_hash VARCHAR2(255) NOT NULL
);

-- 3. Перенос существующих пользователей из USERS по их ролям
INSERT INTO landlords (id, full_name, email, phone, password_hash)
SELECT user_id, full_name, email, phone, password_hash
  FROM users
 WHERE role = 'LANDLORD';

INSERT INTO tenants (id, full_name, email, phone, password_hash)
SELECT user_id, full_name, email, phone, password_hash
  FROM users
 WHERE role = 'TENANT';

-- 4. Переименование колонки owner_id -> landlord_id в PROPERTIES и обновление FK
ALTER TABLE properties RENAME COLUMN owner_id TO landlord_id;

ALTER TABLE properties ADD CONSTRAINT fk_properties_landlord
  FOREIGN KEY (landlord_id) REFERENCES landlords(id);

ALTER TABLE rental_applications ADD CONSTRAINT fk_applications_tenant
  FOREIGN KEY (tenant_id) REFERENCES tenants(id);

ALTER TABLE contracts ADD CONSTRAINT fk_contracts_landlord
  FOREIGN KEY (landlord_id) REFERENCES landlords(id);

ALTER TABLE contracts ADD CONSTRAINT fk_contracts_tenant
  FOREIGN KEY (tenant_id) REFERENCES tenants(id);

-- 5. Удаление устаревшей таблицы USERS (CASCADE CONSTRAINTS снимает старые FK)
DROP TABLE users CASCADE CONSTRAINTS;

COMMIT;

